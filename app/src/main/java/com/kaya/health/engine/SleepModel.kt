package com.kaya.health.engine

import kotlin.math.abs
import kotlin.math.exp
import kotlin.math.ln
import kotlin.math.sqrt

/**
 * Sleep-stage model trained on real sleep-lab nights (Walch et al. 2019, PhysioNet sleep-accel, ODC-By:
 * 31 adults, wrist heart rate + polysomnography labels). Training code: tools/sleep_model/train.py.
 *
 * Held-out accuracy (2-fold cross-validation, people the model never saw):
 *   4 stages 60.8% (kappa 0.37) · asleep vs awake 90.3% · total sleep error 26 min/night.
 * That is in the normal range for heart-rate-only wrist devices.
 *
 * Input: one heart-rate value per 30-s slot (null = missing) and steps in that slot's hour.
 * The feature code MUST stay identical to features() in train.py.
 */
object SleepModel {
    val STAGES = arrayOf(SleepStage.AWAKE, SleepStage.LIGHT, SleepStage.DEEP, SleepStage.REM)

    // ---- generated by tools/sleep_model/train.py ----
    private val MEAN = doubleArrayOf(5.323560, 0.500829, 2.455222, 3.233149, 2.076831, 0.018771, 5.396600, 0.568908, 0.496493, 0.330148, 0.248163)
    private val STD = doubleArrayOf(4.730801, 0.256008, 2.505121, 2.634619, 1.759804, 4.382709, 3.834595, 1.174227, 0.289210, 0.297235, 0.213504)
    private val W = arrayOf(
        doubleArrayOf(0.140607, -0.665984, 0.820038, -0.294661),
        doubleArrayOf(-0.058656, -0.418801, -0.272026, 0.749483),
        doubleArrayOf(-0.338151, 0.517833, 0.666561, -0.846242),
        doubleArrayOf(0.481846, 0.043420, -0.816838, 0.291572),
        doubleArrayOf(0.639311, -0.030414, -1.384851, 0.775954),
        doubleArrayOf(-0.362511, -0.056971, 0.458906, -0.039424),
        doubleArrayOf(-0.096165, 0.366959, -0.515493, 0.244700),
        doubleArrayOf(0.241368, -0.031735, 0.032331, -0.241964),
        doubleArrayOf(-2.450774, 0.496842, 0.331088, 1.622843),
        doubleArrayOf(2.267936, -0.438495, -1.119320, -0.710120),
        doubleArrayOf(0.251086, -0.249436, -0.277788, 0.276138),
        doubleArrayOf(-0.391588, 1.056590, -0.749938, 0.084936), // bias
    )
    // ---- end generated ----

    private const val SMOOTH = 4 // average probabilities over ±2 minutes

    private fun mean(w: List<Int>) = w.average()
    private fun std(w: List<Int>): Double { val m = w.average(); return sqrt(w.sumOf { (it - m) * (it - m) } / w.size) }

    private fun rolling(v: Array<Int?>, i: Int, half: Int, fn: (List<Int>) -> Double): Double? {
        val lo = maxOf(0, i - half); val hi = minOf(v.size, i + half + 1)
        val w = (lo until hi).mapNotNull { v[it] }
        return if (w.size >= maxOf(3, (hi - lo) / 3)) fn(w) else null
    }

    /** numpy.percentile with linear interpolation. */
    private fun percentile(sorted: List<Int>, p: Double): Double {
        val idx = p / 100.0 * (sorted.size - 1)
        val lo = idx.toInt(); val hi = minOf(lo + 1, sorted.size - 1)
        return sorted[lo] + (sorted[hi] - sorted[lo]) * (idx - lo)
    }

    fun features(hr: Array<Int?>, steps: IntArray, first: Int, last: Int): Array<DoubleArray?> {
        val known = hr.filterNotNull().sorted()
        if (known.isEmpty()) return arrayOfNulls(hr.size)
        val base = percentile(known, 10.0)
        val n = hr.size
        val sm5 = Array(n) { rolling(hr, it, 5, ::mean) }
        return Array(n) { i ->
            val h = hr[i]; val s5 = sm5[i]
            if (h == null || s5 == null) return@Array null
            val sd5 = rolling(hr, i, 5, ::std) ?: 0.0
            val sd15 = rolling(hr, i, 15, ::std) ?: 0.0
            val seg = (maxOf(0, i - 5) until minOf(n, i + 6)).mapNotNull { hr[it] }
            val absdiff = if (seg.size >= 3) seg.zipWithNext { a, b -> abs(b - a).toDouble() }.average() else 0.0
            val a = if (i >= 10) sm5[i - 10] else null
            val b = if (i + 10 < n) sm5[i + 10] else null
            val trend = if (a != null && b != null) b - a else 0.0
            val m30 = rolling(hr, i, 30, ::mean)
            // Clamped: training only saw 0..1 (inside the lab night); outside values would lock in a wrong bedtime.
            val frac = ((i - first).toDouble() / maxOf(1, last - first)).coerceIn(0.0, 1.0)
            val rank = known.count { it < s5 }.toDouble() / known.size // numpy searchsorted(side=left)
            doubleArrayOf(
                s5 - base, rank, sd5, sd15, absdiff, trend, (m30 ?: s5) - base,
                ln(1.0 + steps[i]), frac, frac * frac, sd5 / maxOf(1.0, s5 - base + 5),
            )
        }
    }

    private fun softmax(z: DoubleArray): DoubleArray {
        val m = z.max(); val e = z.map { exp(it - m) }; val s = e.sum()
        return e.map { it / s }.toDoubleArray()
    }

    /** Stage for every 30-s slot. [first]/[last] = slots where the sleep period starts/ends. */
    /**
     * @param wakeThreshold if set, a slot is AWAKE only when the smoothed awake probability reaches it; otherwise
     *   the most likely sleep stage. Used when the band's motion sensor already says you were asleep.
     */
    fun classify(hr: Array<Int?>, steps: IntArray, first: Int, last: Int, wakeThreshold: Double? = null): Array<SleepStage> {
        val feats = features(hr, steps, first, last)
        val probs = feats.map { f ->
            f?.let {
                val logits = DoubleArray(4) { k -> W.last()[k] + it.indices.sumOf { j -> (it[j] - MEAN[j]) / STD[j] * W[j][k] } }
                softmax(logits)
            }
        }
        return Array(hr.size) { i ->
            val w = (maxOf(0, i - SMOOTH) until minOf(hr.size, i + SMOOTH + 1)).mapNotNull { probs[it] }
            if (w.isEmpty()) SleepStage.LIGHT
            else if (wakeThreshold != null) {
                val pWake = w.sumOf { it[0] } / w.size
                if (pWake >= wakeThreshold) SleepStage.AWAKE else STAGES[(1 until 4).maxBy { k -> w.sumOf { it[k] } }]
            } else STAGES[(0 until 4).maxBy { k -> w.sumOf { it[k] } }]
        }
    }
}
